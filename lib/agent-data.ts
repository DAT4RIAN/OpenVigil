import type { Agent, AgentLayer, AgentMetrics, AgentStatus } from "./types";

interface AgentDefinition {
  readonly id: string;
  readonly name: string;
  readonly shortName: string;
  readonly layer: AgentLayer;
  readonly role: string;
  readonly description: string;
  readonly status: AgentStatus;
  readonly currentTask: string | null;
  readonly currentMissionId: string | null;
  readonly queueDepth: number;
  readonly skills: readonly string[];
  readonly tools: readonly string[];
  readonly knowledgeSourceIds: readonly string[];
  readonly metrics: AgentMetrics;
  readonly model?: string;
  readonly promptVersion?: string;
  readonly lastActiveAt?: string;
}

const makeAgent = (definition: AgentDefinition): Agent => ({
  ...definition,
  model:
    definition.model ??
    (definition.layer === "review"
      ? "WindOps-Review-14B"
      : definition.layer === "execution"
        ? "WindOps-Executor-14B"
        : "WindOps-Reasoner-32B"),
  promptVersion: definition.promptVersion ?? "2026.08.3",
  lastActiveAt: definition.lastActiveAt ?? "2026-08-13T10:29:42+08:00",
});

