import { readFile, readdir, writeFile, access } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

const start = "<!-- architecture-facts:start -->";
const end = "<!-- architecture-facts:end -->";

export async function architectureFacts(root) {
  const css = await readFile(path.join(root, "app/globals.css"), "utf8");
  const modules = [...css.matchAll(/@import\s+"\.\/styles\/([^"]+)"/g)].map((m) => m[1]);
  if (!modules.length || new Set(modules).size !== modules.length) {
    throw new Error("CSS module inventory is empty or contains duplicates");
  }
  for (const file of modules) await access(path.join(root, "app/styles", file));
  const migrationsDir = path.join(root, "backend/alembic/versions");
  const revisions = new Map();
  for (const file of (await readdir(migrationsDir)).filter((name) => name.endsWith(".py"))) {
    const source = await readFile(path.join(migrationsDir, file), "utf8");
    const revision = source.match(/^revision\s*(?::[^=\n]+)?=\s*["']([^"']+)["']/m)?.[1];
    if (!revision || revisions.has(revision))
      throw new Error(`Invalid/duplicate revision: ${file}`);
    const parent = source.match(
      /^down_revision\s*(?::[^=\n]+)?=\s*(None|["'][^"']+["'])\s*$/m,
    )?.[1];
    if (!parent) throw new Error(`Unsupported migration parent: ${file}`);
    revisions.set(revision, parent === "None" ? null : parent.slice(1, -1));
  }
  const parents = new Set([...revisions.values()].filter(Boolean));
  for (const parent of parents) {
    if (!revisions.has(parent)) throw new Error(`Missing migration parent: ${parent}`);
  }
  const heads = [...revisions.keys()].filter((revision) => !parents.has(revision));
  if (heads.length !== 1) throw new Error(`Expected one migration head, found ${heads.length}`);
  const visited = new Set();
  let revision = heads[0];
  while (revision !== null) {
    if (visited.has(revision)) throw new Error("Migration cycle detected");
    visited.add(revision);
    revision = revisions.get(revision);
  }
  if (visited.size !== revisions.size) throw new Error("Disconnected migration graph");
  return `${start}\n\nGenerated by \`pnpm check:architecture --write\`; CI verifies this inventory against source.\n\n- CSS modules imported by \`app/globals.css\`: **${modules.length}**.\n- Alembic migration head: \`${heads[0]}\`.\n- Ordered CSS modules: ${modules.map((name) => `\`${name}\``).join(", ")}.\n\n${end}`;
}

export async function checkArchitecture(root, write = false) {
  const file = path.join(root, "ARCHITECTURE.md");
  const original = await readFile(file, "utf8");
  const text = original.replaceAll("\r\n", "\n");
  if (
    text.split(start).length !== 2 ||
    text.split(end).length !== 2 ||
    text.indexOf(end) < text.indexOf(start)
  ) {
    throw new Error("ARCHITECTURE.md must contain exactly one ordered facts marker pair");
  }
  const expected = await architectureFacts(root);
  const actual = text.slice(text.indexOf(start), text.indexOf(end) + end.length);
  if (actual === expected) return;
  if (!write)
    throw new Error(
      "Architecture facts drifted. Run pnpm check:architecture --write and review the diff.",
    );
  await writeFile(file, text.replace(actual, expected));
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try {
    await checkArchitecture(process.cwd(), process.argv.includes("--write"));
    console.log("Architecture facts match source.");
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
